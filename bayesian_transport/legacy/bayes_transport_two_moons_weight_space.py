#%% 4) Reconstituted density functional + NLL objective + single optimiser

def _generated_mlp_apply(
    flat: Array,
    value: Array,
    *,
    in_dim: int,
    hidden_dim: int,
    depth: int,
    out_dim: int,
) -> Array:
    """Apply an MLP whose complete weights/biases are stored in one flat vector."""
    h = jnp.reshape(value, (int(in_dim),))
    offset = 0
    d = int(in_dim)

    for _ in range(int(depth)):
        n_w = int(hidden_dim) * d
        w = flat[offset:offset + n_w].reshape((int(hidden_dim), d))
        offset += n_w
        b = flat[offset:offset + int(hidden_dim)]
        offset += int(hidden_dim)
        h = jax.nn.gelu(w @ h + b)
        d = int(hidden_dim)

    n_w = int(out_dim) * d
    w = flat[offset:offset + n_w].reshape((int(out_dim), d))
    offset += n_w
    b = flat[offset:offset + int(out_dim)]
    return w @ h + b


def _realnvp_coupling(flat_parameters: Array, layer_index: int, conditioner: Array) -> tuple[Array, Array]:
    start = int(layer_index) * REALNVP_COUPLING_PARAMETER_COUNT
    stop = start + REALNVP_COUPLING_PARAMETER_COUNT
    raw_shift, raw_log_scale = _generated_mlp_apply(
        flat_parameters[start:stop],
        jnp.reshape(conditioner, (1,)),
        in_dim=1,
        hidden_dim=CFG.posterior_density_hidden_dim,
        depth=CFG.posterior_density_depth,
        out_dim=2,
    )
    # Fixed numerical safeguard inherited from the previous RealNVP version.
    log_scale = 2.0 * jnp.tanh(raw_log_scale)
    return raw_shift, log_scale


def _log_cosh(x: Array) -> Array:
    a = jnp.abs(x)
    return a + jax.nn.softplus(-2.0 * a) - math.log(2.0)


def generated_realnvp_log_prob(flat_parameters: Array, theta: Array) -> Array:
    """Normalized log density on the exact prior support [-1,1]^2.

    The outer tanh map gives compact support. The base density is chosen as
        f(z)=0.5*sech(z)^2
    independently in each coordinate. Therefore when every generated coupling weight is zero,
    tanh(z) is exactly Uniform(-1,1), so the whole initial output density is exactly the paper prior.
    """
    theta = jnp.asarray(theta)

    def one_log_prob(th: Array) -> Array:
        u = (jnp.reshape(th, (2,)) - PRIOR_CENTER) / PRIOR_HALF_WIDTH
        inside = jnp.all(jnp.abs(u) < 1.0)
        safe_u = jnp.clip(u, -1.0 + 1e-6, 1.0 - 1e-6)
        y = jnp.arctanh(safe_u)

        # theta -> y Jacobian from theta = center + half_width*tanh(y)
        log_abs_det_inverse = jnp.sum(
            -math.log(PRIOR_HALF_WIDTH) - jnp.log1p(-safe_u**2)
        )

        # Invert generated affine couplings y -> z.
        for layer_index in range(REALNVP_COUPLINGS - 1, -1, -1):
            transformed = layer_index % 2
            conditioner_idx = 1 - transformed
            shift, log_scale = _realnvp_coupling(
                flat_parameters, layer_index, y[conditioner_idx]
            )
            y = y.at[transformed].set((y[transformed] - shift) * jnp.exp(-log_scale))
            log_abs_det_inverse = log_abs_det_inverse - log_scale

        # Base f(z)=0.5 sech(z)^2 independently in each dimension.
        base_log_prob = jnp.sum(-math.log(2.0) - 2.0 * _log_cosh(y))
        value = base_log_prob + log_abs_det_inverse
        return jnp.where(inside, value, -jnp.inf)

    flat_theta = theta.reshape((-1, 2))
    values = jax.vmap(one_log_prob)(flat_theta)
    return values.reshape(theta.shape[:-1])


def generated_realnvp_sample(flat_parameters: Array, key: Array, n: int) -> Array:
    """Exact samples from the generated bounded-support RealNVP density."""
    # If U~Uniform(-1,1), atanh(U) has density 0.5 sech(z)^2: our chosen base.
    u0 = jax.random.uniform(key, (int(n), 2), minval=-1.0 + 1e-6, maxval=1.0 - 1e-6)
    z = jnp.arctanh(u0)

    def forward_one(z0: Array) -> Array:
        y = z0
        for layer_index in range(REALNVP_COUPLINGS):
            transformed = layer_index % 2
            conditioner_idx = 1 - transformed
            shift, log_scale = _realnvp_coupling(
                flat_parameters, layer_index, y[conditioner_idx]
            )
            y = y.at[transformed].set(y[transformed] * jnp.exp(log_scale) + shift)
        return PRIOR_CENTER + PRIOR_HALF_WIDTH * jnp.tanh(y)

    return jax.vmap(forward_one)(z)


def generated_unnormalized_log_score(flat_parameters: Array, theta: Array) -> Array:
    """Unnormalized neural log-score s_w(theta). There is deliberately no partition function."""
    theta = jnp.asarray(theta)

    def one_score(th: Array) -> Array:
        standardized = (jnp.reshape(th, (2,)) - PRIOR_CENTER) / PRIOR_STD
        return _generated_mlp_apply(
            flat_parameters,
            standardized,
            in_dim=2,
            hidden_dim=CFG.posterior_density_hidden_dim,
            depth=CFG.posterior_density_depth,
            out_dim=1,
        )[0]

    flat_theta = theta.reshape((-1, 2))
    values = jax.vmap(one_score)(flat_theta)
    return values.reshape(theta.shape[:-1])


def generated_density_log_value(flat_parameters: Array, theta: Array) -> Array:
    if CFG.output_density_mode == "realnvp":
        return generated_realnvp_log_prob(flat_parameters, theta)
    return generated_unnormalized_log_score(flat_parameters, theta)


def weight_space_objective(
    model: WeightSpaceBayesTransport,
    prior_theta: Array,
    x_batch: Array,
    target_theta: Array,
    dropout_key: Array,
):
    """One loss only: target NLL for normalized mode, or raw negative score for unnormalized mode."""
    row_keys = jax.random.split(dropout_key, prior_theta.shape[0])
    parameter_sequence = jax.vmap(
        lambda p, x, k: model(p, x, key=k, inference=False)
    )(prior_theta, x_batch, row_keys)  # [B,P,1]
    flat_parameters = parameter_sequence[..., 0]

    target_log_value = jax.vmap(generated_density_log_value)(flat_parameters, target_theta)
    loss = -jnp.mean(target_log_value)

    rms_parameters = jnp.sqrt(jnp.mean(flat_parameters**2) + 1e-12)
    max_abs_parameters = jnp.max(jnp.abs(flat_parameters))
    metrics = {
        "loss": loss,
        "target_nll": loss,
        "mean_target_log_value": jnp.mean(target_log_value),
        "target_log_value_std": jnp.std(target_log_value),
        "generated_parameter_rms": rms_parameters,
        "generated_parameter_max_abs": max_abs_parameters,
    }
    return loss, (metrics, parameter_sequence)


_loss_and_grad = eqx.filter_value_and_grad(weight_space_objective, has_aux=True)


def make_train_step(optimizer: optax.GradientTransformation):
    @eqx.filter_jit
    def step(model, opt_state, prior_theta, x_batch, target_theta, dropout_key):
        (loss, (metrics, parameter_sequence)), grads = _loss_and_grad(
            model, prior_theta, x_batch, target_theta, dropout_key
        )
        params = eqx.filter(model, eqx.is_array)
        updates, opt_state = optimizer.update(grads, opt_state, params)
        model = eqx.apply_updates(model, updates)
        grad_norm = optax.global_norm(eqx.filter(grads, eqx.is_array))
        return model, opt_state, loss, metrics, parameter_sequence, grad_norm
    return step


def _sample_replay_cloud_one(flat_parameters: Array, key: Array) -> Array:
    if CFG.output_density_mode == "realnvp":
        return generated_realnvp_sample(flat_parameters, key, CFG.num_particles)

    # The unnormalized mode has no exact sampler. For replay ONLY, use importance-resampling from
    # a fixed-size Uniform([-1,1]^2) candidate pool. This does not enter the training loss.
    key_candidates, key_indices = jax.random.split(key)
    candidate_count = max(128, 4 * CFG.num_particles)
    candidates = jax.random.uniform(
        key_candidates,
        (candidate_count, 2),
        minval=CFG.prior_low,
        maxval=CFG.prior_high,
    )
    scores = generated_unnormalized_log_score(flat_parameters, candidates)
    ids = jax.random.categorical(key_indices, scores, shape=(CFG.num_particles,))
    return candidates[ids]


@jax.jit
def sample_replay_cloud_batch(flat_parameters: Array, key: Array) -> Array:
    keys = jax.random.split(key, flat_parameters.shape[0])
    return jax.vmap(_sample_replay_cloud_one)(flat_parameters, keys)


