def generated_density_on_grid(
    flat_parameters: np.ndarray,
    theta1_grid: np.ndarray,
    theta2_grid: np.ndarray,
    *,
    chunk_size: int = 8192,
    normalize_for_plot: bool | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Directly evaluate the generated neural density/score at requested theta locations.

    Returns (display_density, raw_log_values). In unnormalized mode, display_density is numerically
    normalized on the plotting grid ONLY for diagnostics; training never uses this normalization.
    """
    g1, g2 = np.meshgrid(theta1_grid, theta2_grid, indexing="xy")
    points = np.column_stack([g1.ravel(), g2.ravel()]).astype(np.float32)
    flat = jnp.asarray(flat_parameters, dtype=jnp.float32)

    chunks = []
    for start in range(0, len(points), int(chunk_size)):
        chunk = jnp.asarray(points[start:start + int(chunk_size)])
        values = generated_density_log_value(flat, chunk)
        chunks.append(np.asarray(jax.device_get(values), dtype=np.float64))
    log_values = np.concatenate(chunks).reshape(g1.shape)

    finite = np.isfinite(log_values)
    if not np.any(finite):
        raise FloatingPointError("Generated density/score is non-finite everywhere on the grid.")
    if CFG.output_density_mode == "realnvp":
        # Keep the actual normalized density scale. Values outside the compact support are -inf.
        density = np.where(finite, np.exp(log_values), 0.0)
    else:
        # An unnormalized score has arbitrary additive scale, so remove its maximum before exponentiating.
        shifted = np.where(finite, log_values - np.max(log_values[finite]), -np.inf)
        density = np.exp(shifted)

    if normalize_for_plot is None:
        # A RealNVP is already analytically normalized. The unnormalized MLP is normalized only
        # on this finite grid for visualization/diagnostic sampling.
        normalize_for_plot = CFG.output_density_mode == "unnormalized_mlp"

    if normalize_for_plot:
        d1 = theta1_grid[1] - theta1_grid[0]
        d2 = theta2_grid[1] - theta2_grid[0]
        z = np.sum(density) * d1 * d2
        if np.isfinite(z) and z > 0:
            density /= z
    return density, log_values


def generated_posterior_samples(
    flat_parameters: np.ndarray,
    theta1_grid: np.ndarray,
    theta2_grid: np.ndarray,
    n: int,
    seed: int,
) -> np.ndarray:
    if CFG.output_density_mode == "realnvp":
        samples = generated_realnvp_sample(
            jnp.asarray(flat_parameters), jax.random.key(seed), int(n)
        )
        return np.asarray(jax.device_get(samples), dtype=np.float32)

    # Experimental unnormalized mode: grid-normalize the score for diagnostic sampling only.
    density, _ = generated_density_on_grid(flat_parameters, theta1_grid, theta2_grid)
    return sample_from_grid_posterior(
        np.random.default_rng(seed), theta1_grid, theta2_grid, density, int(n)
    )


def rolling_mean(x: np.ndarray, window: int = 100) -> np.ndarray:
    x = np.asarray(x, dtype=np.float64)
    if len(x) < 2:
        return x.copy()
    window = max(1, min(int(window), len(x)))
    kernel = np.ones(window, dtype=np.float64) / window
    y = np.convolve(x, kernel, mode="valid")
    return np.concatenate([np.full(window - 1, np.nan), y])


