"""Weight-space Bayes Transport on the Greenberg et al. (2019) two-moons benchmark.

Notebook-style script: run one #%% cell at a time. There is intentionally no main().

The Bayes-Transport model no longer returns posterior particles. Instead it maps
    (input prior particle cloud, x)
onto the *weights and biases* of a small posterior-density network.

Training is simulator-supervised and likelihood-free:
    theta* ~ U([-1,1]^2)
    x ~ simulator(theta*)
    input cloud ~ one of the same three mutually-exclusive training prior sources
    density parameters = T_phi(input cloud, x)
    loss = -log q_{T_phi(input cloud,x)}(theta*)

Only T_phi is trainable. The output density network is a deterministic functional model whose
weights/biases are generated by T_phi on every inference problem.

Two output-density modes are available:
    "realnvp"          : normalized bounded-support RealNVP density (DEFAULT; true NLL)
    "unnormalized_mlp": scalar neural log-score field (experimental; no partition function)

The normalized RealNVP is initialized so that zero generated weights correspond exactly to the
Uniform([-1,1]^2) prior. This pairs naturally with the zero-initialized parameter head.
"""
